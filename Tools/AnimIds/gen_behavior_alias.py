#!/usr/bin/env python3
"""Regenerates WoW/Source/Object/ObjectClient/AnimBehaviorAlias.h from AnimationBehaviorAlias.txt.

  python3 Tools/AnimIds/gen_behavior_alias.py            rewrite the header
  python3 Tools/AnimIds/gen_behavior_alias.py --check    verify only (exit 1 when the header is out of date)

The header holds one entry per extended ground animation (ids 506, 508, ... up to ANIM_COUNT - 2): the behavior the
client classifies that animation as. An id without a line in the .txt maps to itself. See the .txt for the why.
Runs after gen_anim_enum.py (it reads ANIM_COUNT and the native enumerators from Types.h).
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from gen_anim_enum import enumerator, read_names  # noqa: E402

FIRST = 506
# behaviors that set animation-state bits or drive death / airborne handling; classifying a new animation as one of
# these would change client state, not just layering (see the .txt header)
FORBIDDEN = {1, 6, 131, 132, 37, 38, 39, 40, 187, 121, 127, 192, 200, 201, 458, 459, 460, 464, 466, 467, 468, 472}


def main():
    root = os.path.abspath(os.path.join(HERE, '..', '..'))
    ap = argparse.ArgumentParser()
    ap.add_argument('--types', default=os.path.join(root, 'WoW/Source/Object/ObjectClient/Types.h'))
    ap.add_argument('--names', default=os.path.join(HERE, 'AnimationNames.txt'))
    ap.add_argument('--table', default=os.path.join(HERE, 'AnimationBehaviorAlias.txt'))
    ap.add_argument('--out', default=os.path.join(root, 'WoW/Source/Object/ObjectClient/AnimBehaviorAlias.h'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()

    types = open(a.types, 'rb').read().decode('utf-8').replace('\r\n', '\n')
    enum = {}
    for m in re.finditer(r'\b(ANIM_[A-Z0-9_]+)\s*=\s*(0x[0-9A-Fa-f]+|\d+),', types):
        enum[m.group(1)] = int(m.group(2), 0)
    if 'ANIM_COUNT' not in enum:
        sys.exit("ANIM_COUNT not found in " + a.types)
    count = enum['ANIM_COUNT']
    if (count - FIRST) % 2 or count <= FIRST:
        sys.exit(f"ANIM_COUNT {count} does not leave whole ground/FLY pairs after id {FIRST}")
    entries = (count - FIRST) // 2
    native = {v: k for k, v in enum.items() if v < FIRST}

    names = read_names(a.names)
    alias = {}
    for n, raw in enumerate(open(a.table, encoding='utf-8'), 1):
        body, _, comment = raw.partition('#')
        body = body.strip()
        if not body:
            continue
        parts = body.split()
        if len(parts) != 2 or not parts[0].isdigit():
            sys.exit(f"{a.table}:{n}: expected '<id> <BaseName>', got '{body}'")
        i, base = int(parts[0]), parts[1]
        if i < FIRST or i >= count or (i - FIRST) % 2:
            sys.exit(f"{a.table}:{n}: id {i} is not an extended ground animation id ({FIRST}, {FIRST + 2}, ... {count - 2})")
        if i in alias:
            sys.exit(f"{a.table}:{n}: id {i} listed twice")
        e = enumerator(base)
        if e not in enum or enum[e] >= FIRST:
            sys.exit(f"{a.table}:{n}: '{base}' ({e}) is not a native animation enumerator in Types.h")
        if enum[e] in FORBIDDEN:
            sys.exit(f"{a.table}:{n}: '{base}' ({enum[e]}) sets client state; do not alias onto it (see the .txt header)")
        label = comment.split()[0] if comment.split() else ''
        known = names.get(i)
        if label and known and not known.startswith('Unnamed') and known != label:
            sys.exit(f"{a.table}:{n}: id {i} is '{known}' in AnimationNames.txt but the comment says '{label}'")
        alias[i] = (enum[e], base, label)

    rows = []
    for k in range(entries):
        i = FIRST + 2 * k
        if i in alias:
            b, base, label = alias[i]
            rows.append(f"        {b},  // {i} {label} -> {base}")
        else:
            rows.append(f"        {i},  // {i}")
    out = HEADER.format(first=FIRST, entries=entries, n_alias=len(alias), rows='\n'.join(rows))

    eol = '\n'
    if os.path.exists(a.out):
        old = open(a.out, 'rb').read().decode('utf-8')
        eol = '\r\n' if '\r\n' in old else '\n'
        same = old.replace('\r\n', '\n') == out
    else:
        same = False
    if a.check:
        if not same:
            print("AnimBehaviorAlias.h is out of date: run Tools/AnimIds/gen_behavior_alias.py", file=sys.stderr)
            sys.exit(1)
        print(f"up to date: {len(alias)} of {entries} extended animations aliased, ANIM_COUNT = {count}")
        return
    open(a.out, 'wb').write(out.replace('\n', eol).encode('utf-8'))
    print(f"wrote {a.out}: {len(alias)} of {entries} extended animations aliased, ANIM_COUNT = {count}")


HEADER = '''#pragma once

// GENERATED by Tools/AnimIds/gen_behavior_alias.py from Tools/AnimIds/AnimationBehaviorAlias.txt - edit the .txt, not this file.
//
// AnimClassBehavior(): the behavior the client CLASSIFIES an animation as.
//
// An extended animation (id >= {first}) keeps BehaviorID == its own id so that AnimationData::FindIdByBehaviorAndTier can
// find it (and its FLY twin, whose BehaviorID is the ground id). That puts it outside every classifier set in Unit_C.cpp.
// The classifiers therefore read the row's BehaviorID through this function: a listed animation is classified as the
// native animation it is modelled on (torso layering, emote / melee / cast handling, ...); everything else is returned
// unchanged, including every native id, the "no record" sentinel (ANIM_COUNT) and all the special behaviors.
//
// Use it wherever a behavior is compared against a classifier value. Do NOT use it where the behavior is an identity:
// FindIdByBehaviorAndTier, FindDefaultAnimForTier, GetAnimBehaviorId (m_mountAnimBehaviorId is fed back into
// ResolveAnimForModel) and UpdateDisplayInfo's deathAnim keep the raw BehaviorID.

#include <cstdint>

#include "WoW/Source/Object/ObjectClient/Types.h"

constexpr int32_t ANIM_ALIAS_FIRST = {first};    // first extended ground animation id
constexpr int32_t ANIM_ALIAS_COUNT = {entries};    // one entry per ground id: {first}, {first} + 2, ... ANIM_COUNT - 2

static_assert(ANIM_ALIAS_FIRST + 2 * ANIM_ALIAS_COUNT == ANIM_COUNT,
              "ANIM_COUNT changed: re-run Tools/AnimIds/gen_behavior_alias.py (and list the new animations in AnimationBehaviorAlias.txt)");

// {n_alias} of the {entries} entries differ from their own id.
inline int32_t AnimClassBehavior(int32_t behavior) {{
    static const int16_t kClassBehavior[ANIM_ALIAS_COUNT] = {{
{rows}
    }};

    const uint32_t offset = static_cast<uint32_t>(behavior) - static_cast<uint32_t>(ANIM_ALIAS_FIRST);

    if (offset >= static_cast<uint32_t>(2 * ANIM_ALIAS_COUNT) || (offset & 1)) {{
        return behavior;
    }}

    return kClassBehavior[offset >> 1];
}}
'''

if __name__ == '__main__':
    main()
